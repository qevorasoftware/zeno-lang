"""VAJRA step 2 — Piṅgala's laghu/guru binary, implemented for real.

Piṅgala's *Chandaḥśāstra* (c. 3rd century BCE) enumerates poetic metres by
treating each syllable as **laghu (लघु, light)** or **guru (गुरु, heavy)** — a
two-symbol alphabet, i.e. a binary system roughly two millennia before Leibniz.
This module implements the parts that are genuinely algorithmic:

* **prastāra** — the full enumeration of patterns for a metre of ``k`` syllables,
  in the traditional order (all-guru first);
* **naṣṭam** — given a position in that enumeration, recover the pattern (the
  halving algorithm the tradition describes);
* **uddhiṣṭam** — the inverse: the position of a known pattern;
* **meru** — the binomial triangle, whose rows count patterns by number of gurus,
  checked here against :func:`math.comb`;
* **prosody** — real syllable weights computed from a Devanagari/IAST line by the
  ordinary rules (long vowel, conjunct, anusvāra/visarga → guru), so the binary
  is derived from actual sound rather than invented.

And the honest framing, which is the point of putting this in a *security* tree:
a laghu/guru pattern is a **public, invertible encoding**, not a cipher. Nobody
needs to know Piṅgala to invert it — the mapping between bits and light/heavy
syllables is right here in this file. See :func:`confidentiality_report`.

    >>> from aegis.vajra.chandas_binary import nastam, uddistam
    >>> nastam(2, 3)
    'GGL'
    >>> uddistam("GGL")
    2
"""

